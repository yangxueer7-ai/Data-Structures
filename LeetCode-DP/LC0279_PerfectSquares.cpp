/*
 * LeetCode 279. Perfect Squares（完全平方数）
 *
 * 算法：动态规划 + 完全背包（最少数量型）
 *
 * 核心思路：
 * 1. 将所有不超过 n 的正完全平方数 1、4、9、16...
 *    看作可以无限次使用的物品。
 * 2. 背包容量 bagSize = n，目标是恰好凑出 n。
 * 3. dp[j] 表示凑出整数 j 所需的最少完全平方数数量。
 * 4. 状态转移：
 *      dp[j] = min(dp[j], dp[j-x] + 1)
 *    - 不选当前平方数：dp[j]
 *    - 选一个当前平方数：dp[j-x] + 1
 * 5. 完全背包允许重复使用当前物品，因此容量正序遍历。
 *
 * 初始化：
 * 1. dp[0] = 0：凑出 0 最少需要 0 个平方数。
 * 2. 其他位置初始化为 n+1，表示暂时不可达。
 *    因为使用 n 个 1 一定能够凑出 n，
 *    所以 n+1 可以充当无穷大。
 *
 * 易错点：
 * 1. bagSize = n
 * 2. 本题求最少数量，dp[0] = 0；
 *    LC518 求组合数量，dp[0] = 1。
 * 3. 完全背包的内层容量必须正序遍历。
 * 4. 每个平方数可重复选取，不属于 0-1 背包。
 * 5. 枚举平方数从 i=1 开始，不需要将 0 作为物品。
 * 6. 使用 1LL*i*i 避免乘法的 int 溢出风险。
 *
 * 时间复杂度：O(n * sqrt(n))
 * 空间复杂度：O(n)
 */

#include "LeetCodeCommon.h"

using namespace std;

class Solution {
public:
    int numSquares(int n) {

        // dp[j]：凑出整数 j 所需的最少完全平方数数量
        vector<int> dp(n + 1, n + 1);

        // 凑出 0 不需要任何平方数
        dp[0] = 0;

        // 外层枚举物品：所有不超过 n 的正完全平方数
        for (int i = 1; 1LL * i * i <= n; i++) {
            int x = i * i;

            for (int j = x; j <= n; j++) {

                // 不选当前平方数 vs 选一个当前平方数
                dp[j] = min(dp[j], dp[j - x] + 1);
            }
        }

        return dp[n];
    }
};