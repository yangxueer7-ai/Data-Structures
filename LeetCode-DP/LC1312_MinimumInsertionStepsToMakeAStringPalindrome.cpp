/*
 * LeetCode 1312. 让字符串成为回文串的最少插入次数
 * 难度：Hard
 * 分类：动态规划 / 区间 DP / 字符串
 *
 * 【题目描述】
 * 给定字符串 s，每次可以在任意位置插入一个字符。
 * 求使整个字符串成为回文串所需要的最少插入次数。
 *
 * 【解题思路】
 * 方法二：直接使用区间动态规划求解最少插入次数。
 * 根据当前区间首尾字符是否相等，选择不同的状态转移方式。
 *
 * 【状态定义】
 * dp[i][j] 表示将字符串区间 s[i...j] 变成回文串
 * 所需要的最少插入次数。
 *
 * 【状态转移】
 * 1. 当 s[i] == s[j] 时：
 *    首尾字符已经匹配，不需要额外插入字符，
 *    只需要处理内部区间。
 *
 *    dp[i][j] = dp[i+1][j-1];
 *
 * 2. 当 s[i] != s[j] 时：
 *    方案一：在右侧插入 s[i]，匹配左端字符，
 *           剩余区间为 [i+1, j]。
 *    方案二：在左侧插入 s[j]，匹配右端字符，
 *           剩余区间为 [i, j-1]。
 *
 *    两种方案均需要插入一个字符，选择代价较小者。
 *
 *    dp[i][j] = min(dp[i+1][j], dp[i][j-1]) + 1;
 *
 * 【初始化】
 * 整个二维数组初始化为 0。
 * dp[i][i] = 0，因为单个字符本身就是回文串。
 * 空区间同样不需要插入字符，初始值为 0。
 *
 * 【遍历顺序】
 * 外层 i 从 n-1 到 0 倒序遍历；
 * 内层 j 从 i+1 到 n-1 正序遍历。
 * 保证左下方、下方和左方的依赖状态已经计算完成。
 *
 * 【返回值】
 * dp[0][n-1]，即整个字符串的最少插入次数。
 *
 * 【与方法一的区别】
 * 方法一：求最长回文子序列长度 L，返回 n-L。
 * 方法二：直接求最少插入次数，返回 dp[0][n-1]。
 *
 * 【易错点】
 * 1. dp[i][j] 保存的是最少插入次数，而不是回文长度。
 * 2. 对角线初始化为 0，而不是 1。
 * 3. 首尾相等时不需要 +2。
 * 4. 首尾不等时取 min，而不是 max，并且需要 +1。

 *
 * 【复杂度分析】
 * 时间复杂度：O(n^2)
 * 空间复杂度：O(n^2)
 *
 */

#include <iostream>
#include <vector>
#include <string>
#include <algorithm>
using namespace std;

class Solution {
public:
    int minInsertions(string s) {
        int n = s.length();

        vector<vector<int>> dp(n, vector<int>(n, 0));

        for (int i = n - 1; i >= 0; i--) {
            for (int j = i + 1; j < n; j++) {
                if (s[i] == s[j]) {
                    dp[i][j] = dp[i + 1][j - 1];
                }
                else {
                    dp[i][j] = min(dp[i + 1][j], dp[i][j - 1]) + 1;
                }
            }
        }

        return dp[0][n - 1];
    }
};
