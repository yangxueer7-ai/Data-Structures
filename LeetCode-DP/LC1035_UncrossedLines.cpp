/*
 * LeetCode 1035. 不相交的线
 * 难度：Medium
 * 分类：动态规划 / 双序列 DP / LCS
 *
 * 【题目描述】
 * 给定两个整数数组 nums1 和 nums2。
 * 可以在两个数组中数值相等的元素之间绘制连线。
 * 每个元素最多连接一次，并且所有连线不能相交。
 * 求能够绘制的最大连线数量。
 *
 * 【解题思路】
 * 不相交的连线要求匹配元素保持原有的相对顺序，
 * 允许跳过部分元素，但不能改变元素顺序。
 *
 * 因此，本题可以转化为两个整数数组的
 * 最长公共子序列（LCS）问题。
 * 与 LC1143 最长公共子序列的状态转移完全相同。
 *
 * 【状态定义】
 * dp[i][j] 表示 nums1 的前 i 个元素与 nums2 的
 * 前 j 个元素之间能够绘制的最大不相交连线数量。
 *
 * 等价于两个数组对应前缀的最长公共子序列长度。
 *
 * 注意：i 和 j 表示前缀长度，而不是数组下标。
 *
 * 【状态转移】
 * 1. 当 nums1[i-1] == nums2[j-1] 时：
 *    当前两个元素可以匹配，增加一条连线。
 *
 *    dp[i][j] = dp[i-1][j-1] + 1;
 *
 * 2. 当 nums1[i-1] != nums2[j-1] 时：
 *    分别尝试忽略 nums1 或 nums2 的当前末尾元素，
 *    选择能够获得更多连线的方案。
 *
 *    dp[i][j] = max(dp[i-1][j], dp[i][j-1]);
 *
 * 【初始化】
 * DP 数组大小为 (m+1) × (n+1)。
 * 整个二维数组初始化为 0。
 *
 * dp[0][j] = 0;
 * dp[i][0] = 0;
 *
 * 当任意一个数组的前缀为空时，无法绘制连线。
 *
 * 【遍历顺序】
 * 外层 i 从 1 到 m 正序遍历；
 * 内层 j 从 1 到 n 正序遍历。
 * 保证左上方、正上方和正左方的依赖状态已经计算完成。
 *
 * 【返回值】
 * dp[m][n]，即两个完整数组的最大不相交连线数量。
 *
 * 【易错点】
 * 1. DP 下标表示前缀长度，因此数组需要额外开一行一列。
 * 2. 比较当前元素时，原数组下标需要减 1。
 * 3. 匹配成功时增加一条连线，因此只需要 +1。
 * 4. 不匹配时取两种方案的最大值，而不是直接置 0。
 * 5. 本题允许跳过元素，与 LC0718 最长重复子数组不同。
 * 6. 本题不是区间 DP，两层循环均为正序。
 *
 * 【复杂度分析】
 * m 和 n 分别为两个数组的长度。
 * 时间复杂度：O(mn)
 * 空间复杂度：O(mn)

 */

#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int maxUncrossedLines(vector<int>& nums1, vector<int>& nums2) {
        int m = nums1.size();
        int n = nums2.size();

        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        for (int i = 1; i <= m; i++) {
            for (int j = 1; j <= n; j++) {
                if (nums1[i - 1] == nums2[j - 1]) {
                    dp[i][j] = dp[i - 1][j - 1] + 1;
                }
                else {
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);
                }
            }
        }

        return dp[m][n];
    }
};
