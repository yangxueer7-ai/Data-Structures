/*
 * LeetCode 120. Triangle
 * 题目：三角形最小路径和
 *
 * ============================================================
 * 解法一：二维 DP（自顶向下）
 * ============================================================
 *
 * 核心思路：
 * dp[i][j] 表示：
 * 从三角形顶点走到 triangle[i][j] 的最小路径和。
 *
 * 状态转移：
 *
 * 1. 最左边：
 *    只能从右上方来
 *    dp[i][0] = dp[i - 1][0] + triangle[i][0]
 *
 * 2. 最右边：
 *    只能从左上方来
 *    dp[i][i] = dp[i - 1][i - 1] + triangle[i][i]
 *
 * 3. 中间位置：
 *    可以从左上 / 右上来
 *    dp[i][j] =
 *        min(dp[i - 1][j - 1], dp[i - 1][j])
 *        + triangle[i][j]
 *
 * 注意：
 * 第 i 行有 i + 1 个元素，
 * 有效下标为 0 ~ i。
 *
 * 最终答案：
 * 最后一行中的最小值。
 *
 * 时间复杂度：O(n^2)
 * 空间复杂度：O(n^2)
 *
 * ============================================================
 * ★ 解法二：一维 DP（自底向上）
 * ============================================================
 *
 * 核心思路：
 * 直接把最后一行复制到 dp 中，
 * 然后从倒数第二行开始，一层一层往上压缩。
 *
 * 对于 triangle[i][j]：
 *
 * 左下：
 * dp[j]
 *
 * 右下：
 * dp[j + 1]
 *
 * 状态转移：
 *
 * dp[j] =
 *     min(dp[j], dp[j + 1])
 *     + triangle[i][j]
 *
 * 每处理完一层：
 * dp 的前 i + 1 个位置就表示
 * “从当前这一层各位置出发到底部的最小路径和”。
 *
 * 最后只剩一个顶点：
 * dp[0] 即为答案
 *
 * 时间复杂度：O(n^2)
 * 空间复杂度：O(n)
 *
 * ============================================================
 * 易错点
 * ============================================================
 *
 * 1. triangle 不是普通矩形二维数组。
 *    第 i 行元素数量 = i + 1。
 *
 * 2. 自顶向下：
 *    左上 = dp[i - 1][j - 1]
 *    右上 = dp[i - 1][j]
 *
 * 3. 自底向上：
 *    左下 = dp[j]
 *    右下 = dp[j + 1]
 *
 * 4. 二维 DP 最后不是固定返回某个位置，
 *    而是取最后一行最小值。
 *
 * 5. 一维自底向上最终直接返回 dp[0]。
 */

#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

// ============================================================
// 解法一：二维 DP，自顶向下
// ============================================================

class Solution120_D1 {
public:
    int minimumTotal(vector<vector<int>>& triangle) {
        int n = triangle.size();

        vector<vector<int>> dp(n, vector<int>(n));

        // 顶点
        dp[0][0] = triangle[0][0];

        // 从第 1 行开始往下计算
        for (int i = 1; i < n; i++) {

            // 最左边：只能从右上方来
            dp[i][0] =
                dp[i - 1][0] + triangle[i][0];

            // 中间位置
            for (int j = 1; j < i; j++) {
                dp[i][j] =
                    min(
                        dp[i - 1][j - 1],   // 左上
                        dp[i - 1][j]        // 右上
                    )
                    + triangle[i][j];
            }

            // 最右边：只能从左上方来
            dp[i][i] =
                dp[i - 1][i - 1] + triangle[i][i];
        }

        // 最后一行取最小值
        int ans = dp[n - 1][0];

        for (int j = 1; j < n; j++) {
            ans = min(ans, dp[n - 1][j]);
        }

        return ans;
    }
};


// ============================================================
// 解法二：一维 DP，自底向上
// ============================================================

class Solution120_D2 {
public:
    int minimumTotal(vector<vector<int>>& triangle) {
        int n = triangle.size();

        // 直接用最后一行初始化 dp
        vector<int> dp = triangle[n - 1];

        // 从倒数第二行开始，一层层往上更新
        for (int i = n - 2; i >= 0; i--) {

            for (int j = 0; j <= i; j++) {

                // dp[j]     = 左下
                // dp[j + 1] = 右下
                dp[j] =
                    min(dp[j], dp[j + 1])
                    + triangle[i][j];
            }
        }

        // 最后压缩到顶点
        return dp[0];
    }
};