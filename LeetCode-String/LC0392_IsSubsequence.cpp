
/*
 * ============================================================
 * LeetCode 392. 判断子序列 (Is Subsequence)
 * 难度：Easy
 * 专题：String / Two Pointers 
 *
 * 【核心思路】
 * 1. 使用双指针 i、j 分别遍历字符串 s 和 t。
 * 2. j 负责扫描 t，寻找 s 中当前需要匹配的字符。
 * 3. 如果 s[i] == t[j]，匹配成功，i++。
 * 4. 无论是否匹配成功，j 每轮都必须向右移动。
 * 5. 如果 i == s.size()，说明 s 全部匹配成功。
 *
 * 【双指针含义】
 * i：s 中下一个需要匹配的字符。
 * j：t 中当前正在检查的字符。
 *
 * 【核心逻辑】
 * while (i < s.size() && j < t.size()) {
 *     if (s[i] == t[j]) {
 *         i++;
 *     }
 *     j++;
 * }
 *
 * return i == s.size();
 *
 * 【易错点】
 * 1. j++ 必须放在 if 外面，每轮都要移动。
 * 2. 不能把 j++ 只写在 else 中，
 *    否则同一个 t[j] 可能被重复匹配。
 * 3. 必须先比较字符，再移动 j，避免漏掉字符或越界。
 * 4. 最终判断 i == s.size()，不是 j == t.size()。
 * 5. 子序列可以不连续，但相对顺序不能改变。
 * 6. 空字符串 s 是任何字符串的子序列。
 *
 * 【复杂度】
 * 时间：O(m)，m 为字符串 t 的长度。
 * 空间：O(1)，只使用两个辅助指针。
 *
 * j 负责寻找，i 负责匹配；
 * 匹配成功 i++，每轮扫描 j++。
 * ============================================================
 */

#include <string>

using namespace std;

class Solution392 {
public:
    bool isSubsequence(string s, string t) {
        int i = 0;
        int j = 0;

        while (i < s.size() && j < t.size()) {
            if (s[i] == t[j]) {
                i++;
            }

            j++;
        }

        return i == s.size();
    }
};