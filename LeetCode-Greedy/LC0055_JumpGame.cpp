/*
 * LeetCode 55. Jump Game
 * 题目：跳跃游戏
 *
 * 核心思路：贪心。
 *
 * nums[i] 表示：
 * 站在下标 i 时，最多可以向右跳 nums[i] 步。
 *
 * 题目问的是：
 * 是否能够从下标 0 出发，到达最后一个位置。
 *
 * 注意：
 * nums[i] 表示“最多跳多少步”，
 * 并不是必须跳这么多步。
 *
 * ------------------------------------------------------------
 * 核心变量：
 *
 * maxReach：
 * 表示目前为止能够到达的最远下标。
 *
 * 当遍历到位置 i 时：
 * 如果：
 * i > maxReach
 * 说明当前位置根本无法到达，
 * 后面的位置自然也无法继续处理，
 * 返回 false。
 *
 * 如果当前位置可以到达：
 * 当前从 i 最远可以跳到：
 * i + nums[i]
 *
 * 所以更新：
 * maxReach = max(maxReach, i + nums[i]);
 *
 * 如果：
 * maxReach >= n - 1
 *
 * 说明已经能够到达最后一个位置，
 * 返回 true。
 * ------------------------------------------------------------
 * 核心理解：
 * 不需要真的决定“每一步具体跳到哪里”，
 * 只需要不断维护：
 * “截至目前，我最远能覆盖到哪里？”
 *
 * 只要当前位置仍然在覆盖范围内，
 * 就可以继续利用当前位置扩大覆盖范围。

 * 只维护当前最远能到达的位置。
 * ------------------------------------------------------------
 * 特殊情况：
 * n == 1：
 * 起点就是终点，
 * 不需要跳，直接返回 true。
 *
 * ------------------------------------------------------------
 * 易错点：
 *
 * 1. nums[i] 是“最多跳 nums[i] 步”，不是必须跳。
 *
 * 2. 当前下标 i 必须满足：
 *
 *    i <= maxReach
 *
 *    才说明这个位置能够到达。
 *
 * 3. 不是判断 nums[i] 是否为 0，
 *    因为某个 0 位置可能可以直接被前面的跳跃跨过去而可以被忽视。
 *
 * 4. 判断能否到达终点，看的是：
 *
 *    maxReach >= n - 1
 *
 * 时间复杂度：O(n)
 * 空间复杂度：O(1)
 */

#include <vector>

using namespace std;

class Solution55 {
public:
    bool canJump(vector<int>& nums) {
        int n = nums.size();

        if (n == 0) {
            return false;
        }

        int maxReach = 0;

        for (int i = 0; i < n; i++) {

            // 当前这个位置已经无法到达
            if (i > maxReach) {
                return false;
            }

            // 更新目前最远能够到达的位置
            maxReach = max(maxReach, i + nums[i]);

            // 已经能够覆盖终点
            if (maxReach >= n - 1) {
                return true;
            }
        }

        return true;
    }
};
