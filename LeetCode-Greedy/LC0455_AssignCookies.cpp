
/*
 * ============================================================
 * LeetCode 455. 分发饼干 (Assign Cookies)
 * 难度：Easy
 * 专题：Greedy / Sorting / Two Pointers
 *
 * 【核心思路】
 * 1. 将孩子胃口 g 和饼干大小 s 分别升序排序。
 * 2. 从后往前遍历，优先用大饼干满足大胃口的孩子。
 * 3. 如果最大饼干仍无法满足当前孩子，跳过该孩子。
 * 4. 如果能够满足，则分配饼干，满足人数 +1。
 *
 * 【双指针】
 * i：当前胃口最大的未处理孩子。
 * j：当前最大的未使用饼干。
 *
 * s[j] < g[i]：
 *     当前孩子无法被满足，i--。
 *
 * s[j] >= g[i]：
 *     匹配成功，i--、j--、ans++。
 *
 * 【贪心依据】
 * 如果最大的饼干都无法满足当前最大的胃口，
 * 那么其他更小的饼干也无法满足这个孩子。
 * 因此可以安全地跳过该孩子。
 *
 * 【易错点】
 * 1. 从后往前遍历，循环条件必须是 i >= 0 && j >= 0。
 * 2. i == 0 和 j == 0 时，仍然有元素需要处理。
 * 3. 初始化下标时注意 size() 是无符号整数：
 *    int i = (int)g.size() - 1;
 * 4. 匹配失败时只移动 i，不能浪费当前最大饼干。
 * 5. 匹配成功时两个指针都要移动。
 *
 * 【复杂度】
 * 时间：O(n log n + m log m)，主要来自排序。
 * 额外空间：双指针 O(1)，排序辅助空间依实现而定。
 *
 * 排序后从大到小匹配；
 * 满足则双指针左移，不满足则跳过大胃口孩子。
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

class Solution455 {
public:
    int findContentChildren(vector<int>& g, vector<int>& s) {
        sort(g.begin(), g.end());
        sort(s.begin(), s.end());

        int i = (int)g.size() - 1;
        int j = (int)s.size() - 1;
        int ans = 0;

        while (i >= 0 && j >= 0) {
            // 最大的饼干满足不了胃口最大的孩子
            if (s[j] < g[i]) {
                i--;
            }

            else {
                i--;
                j--;
                ans++;
            }
        }

        return ans;
    }
};
