/*
 * LeetCode 75. Sort Colors
 * 题目：颜色分类
 *
 * ============================================================
 * 解法一：计数 + 覆盖（自己的思路）
 * ============================================================
 *
 * 核心思路：
 *
 * 数组中只会出现：
 * 0、1、2
 * 所以可以：
 * 1. 扫描数组，把所有 0 写到前面
 * 2. 同时统计 1 的个数
 * 3. 扫描结束后，在 0 后面补 countOne 个 1
 * 4. 剩下位置全部补 2
 *
 * slow：
 * 指向下一个 0 应该写入的位置。
 *
 * countOne：
 * 记录数组中 1 的数量。
 *
 * fast：
 * 从头到尾扫描整个数组。
 *
 *
 * 因为始终有：
 *
 * slow <= fast
 *
 * slow 只会写入已经扫描过的位置，
 * 不会覆盖 fast 右边还没有检查的数据。
 *
 * 关键理解：
 * 先把 0 区整理出来，
 * 再根据 1 的数量补出 1 区，
 * 剩余自然全部属于 2 区。
 *
 * 易错点：
 * 1. 遇到 1 时只统计数量，不需要立即写入。
 * 2. 填 1 的区间：
 *
 *    [slow, slow + countOne)
 *
 * 3. 所以填 2 必须从：
 *    slow + countOne
 *    开始，不能多 +1。
 * 4. fast 建议从头往后扫描，避免覆盖未处理区域。
 *
 * 时间复杂度：O(n)
 * 空间复杂度：O(1)
 *
 * ============================================================
 * 解法二：三指针 / 荷兰国旗算法
 * ============================================================
 *
 * 核心思路：
 * 使用三个下标：
 * low：
 * 指向下一个 0 应该放的位置。
 *
 * cur：
 * 指向当前正在检查的位置。
 *
 * high：
 * 指向下一个 2 应该放的位置。
 * 数组可以看成四个区域：
 *
 * [ 0区 | 1区 | 未处理区 | 2区 ]
 *
 * 其中：
 *
 * 0 ~ low-1       都是 0
 * low ~ cur-1     都是 1
 * cur ~ high      还没处理
 * high+1 ~ n-1    都是 2
 *
 * 情况 1：
 * nums[cur] == 0
 *
 * 把 0 交换到左边：
 *
 * swap(nums[cur], nums[low]);
 * low++;
 * cur++;
 *
 * 情况 2：
 * nums[cur] == 1
 *
 * 1 本来就应该留在中间：
 * cur++;
 * 
 * 情况 3：
 * nums[cur] == 2
 *
 * 把 2 交换到右边：
 *
 * swap(nums[cur], nums[high]);
 * high--;
 *
 * 注意：
 * 此时 cur 不能 ++。
 *
 * 因为从 high 位置交换过来的新元素
 * 还没有被检查过，
 * 所以必须继续检查当前 cur。
 *
 *
 * 0 往左扔，
 * 2 往右扔，
 * 1 留中间。
 * 易错点：
 *
 * 1. 遇到 0：
 *    low++，cur++
 *
 * 2. 遇到 1：
 *    只 cur++
 *
 * 3. 遇到 2：
 *    只 high--
 *    cur 不动
 *
 * 4. 循环条件：
 *    cur <= high
 *    因为 high 位置本身也属于未处理区域。
 *
 *
 * 时间复杂度：O(n)
 * 空间复杂度：O(1)
 */

#include <vector>
#include <algorithm>

using namespace std;

// ============================================================
// 解法一：计数 + 覆盖
// ============================================================

class SolutionCount {
public:
    void sortColors(vector<int>& nums) {
        int n = nums.size();

        int slow = 0;
        int countOne = 0;

        // 扫描数组：
        // 0 写到前面，1 只统计数量
        for (int fast = 0; fast < n; fast++) {
            if (nums[fast] == 0) {
                nums[slow] = 0;
                slow++;
            }
            else if (nums[fast] == 1) {
                countOne++;
            }
        }

        // 补 1
        for (int i = slow; i < slow + countOne; i++) {
            nums[i] = 1;
        }

        // 剩下全部补 2
        for (int i = slow + countOne; i < n; i++) {
            nums[i] = 2;
        }
    }
};


// ============================================================
// 解法二：三指针 / 荷兰国旗算法
// ============================================================

class SolutionThreePointers {
public:
    void sortColors(vector<int>& nums) {
        int low = 0;
        int cur = 0;
        int high = nums.size() - 1;

        while (cur <= high) {

            // 0 应该放到左边
            if (nums[cur] == 0) {
                swap(nums[cur], nums[low]);
                low++;
                cur++;
            }

            // 1 本来就在中间
            else if (nums[cur] == 1) {
                cur++;
            }

            // 2 应该放到右边
            else {
                swap(nums[cur], nums[high]);
                high--;

                // cur 不动
                // 因为换过来的元素还没检查
            }
        }
    }
};